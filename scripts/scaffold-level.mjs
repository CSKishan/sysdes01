function main() {
  const args = parseArgs(process.argv.slice(2))
  for (const required of ['id', 'chapter', 'title', 'concept']) {
    if (!args[required]) fail(`--${required} is required`)
  }
  if (!/^[a-z0-9]+-[a-z0-9-]+$/.test(args.id)) fail(`--id "${args.id}" should look like "ch2-federation"`)

  const skeleton = levelSkeleton({
    id: args.id,
    chapterId: args.chapter,
    order: args.order ?? '0 /* TODO: position within the chapter */',
    title: args.title,
    concept: args.concept,
    analogy: args.analogy ?? 'TODO: the delivery-company name for this',
  })

  if (!args.write) {
    console.log(skeleton)
    console.log(
      `\n// Not written to disk -- pass --write to append to src/content/${args.chapter}-extra.ts, or paste this into an existing chapter file yourself (remember to add the const to that file's exported *_LEVELS array).`,
    )
    return
  }

  const targetFile = path.join(CONTENT_DIR, `${args.chapter}-extra.ts`)
  if (!existsSync(targetFile)) {
    writeFileSync(
      targetFile,
      `// Overflow content for ${args.chapter} -- created by scripts/scaffold-level.mjs.
// Remember to import this chapter's *_LEVELS export from wherever the
// chapter's main file assembles its level list (see how chapter1.ts pulls
// in chapter1-extra.ts for the existing pattern).

import type { Level } from './types'
import type { SimGraph } from '@/engine/types'
import { constantTraffic } from '@/engine/traffic'
import { client } from './graphHelpers'
`,
    )
    console.log(`Created ${path.relative(process.cwd(), targetFile)}`)
  }
  appendFileSync(targetFile, skeleton)
  console.log(`Appended "${args.id}" to ${path.relative(process.cwd(), targetFile)}`)
  console.log('Remember to: add it to that file\'s exported level array, and wire that array into registry.ts if this is a new chapter file.')
}

main()
