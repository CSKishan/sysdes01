// Phase 10.5: generates a new level's starting skeleton -- every field
// content-lint (src/content/__tests__/contentLint.test.ts) actually checks,
// pre-filled with clearly-marked TODOs rather than left out, so a content
// author fills in prose instead of hunting through types.ts for what shape
// a level even needs. Not wired into any other script; run by hand.
//
// Usage:
//   node scripts/scaffold-level.mjs --id ch2-federation --chapter ch2 \
//     --order 15 --title "Separate Books, One Front Desk" \
//     --concept "Database Federation" --analogy "The Regional Ledger"
//
// Writes the skeleton to stdout by default; pass --write to append it to
// src/content/<chapter>-extra.ts instead (creating the file, with the
// import/export scaffolding, if it doesn't exist yet).

import { existsSync, appendFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const CONTENT_DIR = path.join(__dirname, '..', 'src', 'content')

function parseArgs(argv) {
  const args = {}
  for (let i = 0; i < argv.length; i++) {
    if (!argv[i].startsWith('--')) continue
    const key = argv[i].slice(2)
    if (key === 'write') {
      args.write = true
      continue
    }
    args[key] = argv[i + 1]
    i++
  }
  return args
}

function fail(message) {
  console.error(`error: ${message}`)
  process.exit(1)
}

function camelCase(id) {
  return id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
}

